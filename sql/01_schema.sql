-- CASE 15: Telecommunications Management System
-- PostgreSQL 14+
-- Run scripts in numerical order in a fresh database named telecom_case15.
BEGIN;
CREATE TABLE branches (
 branch_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(100) NOT NULL, city VARCHAR(80) NOT NULL,
 address TEXT NOT NULL, phone VARCHAR(20)
);
CREATE TABLE employees (
 employee_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 branch_id BIGINT NOT NULL REFERENCES branches(branch_id),
 full_name VARCHAR(120) NOT NULL, position VARCHAR(80) NOT NULL,
 hired_at DATE NOT NULL DEFAULT CURRENT_DATE,
 salary NUMERIC(12,2) NOT NULL CHECK (salary >= 0)
);
CREATE TABLE subscribers (
 subscriber_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 full_name VARCHAR(120) NOT NULL,
 iin VARCHAR(12) UNIQUE NOT NULL CHECK (iin ~ '^[0-9]{12}$'),
 email VARCHAR(150) UNIQUE, phone VARCHAR(20) NOT NULL UNIQUE,
 registered_at DATE NOT NULL DEFAULT CURRENT_DATE,
 status VARCHAR(15) NOT NULL DEFAULT 'active' CHECK (status IN ('active','blocked','inactive')),
 branch_id BIGINT REFERENCES branches(branch_id)
);
CREATE TABLE sim_cards (
 sim_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 iccid VARCHAR(22) NOT NULL UNIQUE,
 msisdn VARCHAR(20) NOT NULL UNIQUE,
 subscriber_id BIGINT REFERENCES subscribers(subscriber_id),
 activated_at DATE,
 status VARCHAR(15) NOT NULL DEFAULT 'available' CHECK (status IN ('available','active','blocked')),
 CHECK ((subscriber_id IS NULL AND status = 'available') OR subscriber_id IS NOT NULL)
);
CREATE TABLE tariffs (
 tariff_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(80) NOT NULL UNIQUE,
 monthly_fee NUMERIC(12,2) NOT NULL CHECK (monthly_fee >= 0),
 included_minutes INTEGER NOT NULL CHECK (included_minutes >= 0),
 included_sms INTEGER NOT NULL CHECK (included_sms >= 0),
 included_gb NUMERIC(10,2) NOT NULL CHECK (included_gb >= 0),
 extra_minute_price NUMERIC(10,2) NOT NULL DEFAULT 0 CHECK (extra_minute_price >= 0),
 extra_gb_price NUMERIC(10,2) NOT NULL DEFAULT 0 CHECK (extra_gb_price >= 0),
 is_active BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE subscriptions (
 subscription_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 subscriber_id BIGINT NOT NULL REFERENCES subscribers(subscriber_id),
 sim_id BIGINT NOT NULL REFERENCES sim_cards(sim_id),
 tariff_id BIGINT NOT NULL REFERENCES tariffs(tariff_id),
 start_date DATE NOT NULL,
 end_date DATE,
 status VARCHAR(12) NOT NULL DEFAULT 'active' CHECK (status IN ('active','ended')),
 CHECK (end_date IS NULL OR end_date >= start_date),
 UNIQUE(subscriber_id,sim_id,start_date)
);
CREATE UNIQUE INDEX ux_subscriptions_one_active_per_sim ON subscriptions(sim_id) WHERE status = 'active';
CREATE TABLE tariff_history (
 history_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 subscriber_id BIGINT NOT NULL REFERENCES subscribers(subscriber_id),
 sim_id BIGINT NOT NULL REFERENCES sim_cards(sim_id),
 old_tariff_id BIGINT REFERENCES tariffs(tariff_id),
 new_tariff_id BIGINT NOT NULL REFERENCES tariffs(tariff_id),
 changed_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 reason TEXT
);
CREATE TABLE calls (
 call_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 sim_id BIGINT NOT NULL REFERENCES sim_cards(sim_id),
 called_number VARCHAR(20) NOT NULL,
 started_at TIMESTAMP NOT NULL,
 duration_seconds INTEGER NOT NULL CHECK (duration_seconds >= 0),
 call_type VARCHAR(12) NOT NULL DEFAULT 'outgoing' CHECK (call_type IN ('outgoing','incoming'))
);
CREATE TABLE sms_usage (
 sms_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 sim_id BIGINT NOT NULL REFERENCES sim_cards(sim_id),
 recipient_number VARCHAR(20) NOT NULL,
 sent_at TIMESTAMP NOT NULL,
 sms_count INTEGER NOT NULL DEFAULT 1 CHECK (sms_count > 0)
);
CREATE TABLE internet_usage (
 usage_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 sim_id BIGINT NOT NULL REFERENCES sim_cards(sim_id),
 usage_date DATE NOT NULL,
 mb_used NUMERIC(14,2) NOT NULL CHECK (mb_used >= 0)
);
CREATE TABLE service_packages (
 package_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(100) NOT NULL UNIQUE,
 package_type VARCHAR(15) NOT NULL CHECK (package_type IN ('internet','minutes','sms')),
 allowance NUMERIC(12,2) NOT NULL CHECK (allowance > 0),
 price NUMERIC(12,2) NOT NULL CHECK (price >= 0),
 validity_days INTEGER NOT NULL CHECK (validity_days > 0)
);
CREATE TABLE subscriber_packages (
 subscriber_package_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 subscriber_id BIGINT NOT NULL REFERENCES subscribers(subscriber_id),
 package_id BIGINT NOT NULL REFERENCES service_packages(package_id),
 purchased_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 expires_at TIMESTAMP NOT NULL,
 CHECK (expires_at > purchased_at)
);
CREATE TABLE invoices (
 invoice_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 subscriber_id BIGINT NOT NULL REFERENCES subscribers(subscriber_id),
 billing_month DATE NOT NULL CHECK (EXTRACT(DAY FROM billing_month) = 1),
 tariff_fee NUMERIC(12,2) NOT NULL CHECK (tariff_fee >= 0),
 extra_charges NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (extra_charges >= 0),
 total_amount NUMERIC(12,2) GENERATED ALWAYS AS (tariff_fee + extra_charges) STORED,
 issued_at DATE NOT NULL DEFAULT CURRENT_DATE,
 due_date DATE NOT NULL,
 status VARCHAR(12) NOT NULL DEFAULT 'unpaid' CHECK (status IN ('unpaid','partial','paid')),
 UNIQUE(subscriber_id,billing_month)
);
CREATE TABLE payments (
 payment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 invoice_id BIGINT NOT NULL REFERENCES invoices(invoice_id),
 subscriber_id BIGINT NOT NULL REFERENCES subscribers(subscriber_id),
 amount NUMERIC(12,2) NOT NULL CHECK (amount > 0),
 payment_method VARCHAR(20) NOT NULL CHECK (payment_method IN ('card','cash','bank_transfer')),
 paid_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE complaints (
 complaint_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 subscriber_id BIGINT NOT NULL REFERENCES subscribers(subscriber_id),
 employee_id BIGINT REFERENCES employees(employee_id),
 subject VARCHAR(150) NOT NULL,
 description TEXT NOT NULL,
 status VARCHAR(15) NOT NULL DEFAULT 'open' CHECK (status IN ('open','in_progress','resolved')),
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 resolved_at TIMESTAMP
);
CREATE INDEX ix_calls_sim_date ON calls(sim_id,started_at);
CREATE INDEX ix_internet_sim_date ON internet_usage(sim_id,usage_date);
CREATE INDEX ix_payments_invoice ON payments(invoice_id);
CREATE INDEX ix_subscriptions_subscriber ON subscriptions(subscriber_id);
COMMIT;
